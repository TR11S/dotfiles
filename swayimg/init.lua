-- swayimg config: only what differs from the defaults.
-- Defaults: /usr/share/swayimg/example.lua

swayimg.decoration = false
swayimg.imagelist.adjacent = true

swayimg.text.font = "Terminess Nerd Font"
-- Must not be 12-24 even, 28 or 32: Terminess has 1-bit bitmaps at those sizes,
-- and swayimg reads glyphs as 8-bit, which draws them as diagonal stripes.
swayimg.text.size = 19

swayimg.gallery.pstore = true
swayimg.gallery.aspect = "fit"

swayimg.viewer.autopos = "follow"
swayimg.viewer.text = {
  topleft = { "{name}" },
  topright = { "{list.index} of {list.total}" },
  bottomleft = { "{frame.width}x{frame.height}  {scale}" },
}

swayimg.format_conf = { video = { enable = false } }

-- Colors are generated by wallust (templates/swayimg.lua).
pcall(dofile, os.getenv("HOME") .. "/.config/swayimg/colors.lua")

-- Quote a path for the shell.
local function q(path)
  return "'" .. path:gsub("'", "'\\''") .. "'"
end

local function trash(path)
  -- swayimg embeds LuaJIT: os.execute returns the exit code, not a boolean
  if os.execute("gio trash " .. q(path)) == 0 then
    swayimg.imagelist.remove(path)
    return true
  end
  return false
end

local function bind_actions(mode)
  local function with_path(fn)
    return function()
      local img = mode.get_image()
      if img then
        fn(img.path)
      end
    end
  end

  -- move current image to trash
  mode.on_key("d", with_path(function(path)
    swayimg.text.status = trash(path) and "Moved to trash" or "Trash failed"
  end))

  -- move all marked images to trash
  mode.on_key("Shift+d", function()
    local moved, failed = 0, 0
    for _, entry in ipairs(swayimg.imagelist.get()) do
      if entry.mark then
        if trash(entry.path) then
          moved = moved + 1
        else
          failed = failed + 1
        end
      end
    end
    swayimg.text.status = moved .. " moved to trash, " .. failed .. " failed"
  end)

  -- copy image data to clipboard
  mode.on_key("y", with_path(function(path)
    local p = q(path)
    os.execute('wl-copy --type "$(file --brief --mime-type ' .. p .. ')" < ' .. p)
    swayimg.text.status = "Image copied"
  end))

  -- copy path to clipboard
  mode.on_key("Shift+y", with_path(function(path)
    os.execute("printf %s " .. q(path) .. " | wl-copy")
    swayimg.text.status = "Path copied"
  end))

  -- set as wallpaper (in the background; fuzzel-settings notifies on failure)
  mode.on_key("w", with_path(function(path)
    os.execute("fuzzel-settings wallpaper-set " .. q(path) .. " >/dev/null 2>&1 &")
    swayimg.text.status = "Setting wallpaper"
  end))
end

bind_actions(swayimg.viewer)
bind_actions(swayimg.gallery)

-- The default handler moves the image along with the scroll direction, the
-- opposite of a document. Setting on_scroll replaces it, so zoom is kept here.
local function bind_scroll(mode)
  mode.on_scroll(function(kmods, horizontal, vertical)
    if kmods == "Ctrl" then
      local mouse = swayimg.get_mouse_pos()
      local scale = mode.scale
      mode.set_abs_scale(scale - scale * vertical / 10.0, mouse.x, mouse.y)
    else
      local pos = mode.get_position()
      local dx = math.modf(horizontal * 50)
      local dy = math.modf(vertical * 50)
      mode.set_abs_position(pos.x - dx, pos.y - dy)
    end
  end)
end

bind_scroll(swayimg.viewer)
bind_scroll(swayimg.slideshow)

-- left/right switch images instead of panning (up/down still pan)
local function bind_switch(mode)
  mode.on_key("Right", function()
    mode.open("next")
  end)
  mode.on_key("Left", function()
    mode.open("prev")
  end)
end

bind_switch(swayimg.viewer)
bind_switch(swayimg.slideshow)
